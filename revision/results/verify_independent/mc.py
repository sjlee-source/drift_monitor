"""Plain Monte Carlo of delayed Bernoulli CUSUM, vectorized over replicates.
Informative origins generated by geometric gaps (equivalent to independent
Bernoulli(rho) per item); miss ~ Bernoulli(r(origin)); alarm T = origin + d."""
import numpy as np


def simulate(h, p, rho, r_fn, s_max, d, n_rep, seed, r0=0.10, chunk=100000):
    a = np.log(p / r0); b = np.log((1 - p) / (1 - r0))
    rng = np.random.default_rng(seed)
    T_all = []
    for c0 in range(0, n_rep, chunk):
        n = min(chunk, n_rep - c0)
        S = np.zeros(n)
        origin = np.zeros(n, dtype=np.int64)
        T = np.full(n, -1, dtype=np.int64)  # -1 = no alarm within s_max
        alive = np.ones(n, dtype=bool)
        while alive.any():
            ia = np.nonzero(alive)[0]
            origin[ia] += rng.geometric(rho, size=ia.size)
            over = origin[ia] > s_max
            alive[ia[over]] = False
            ia = ia[~over]
            o = origin[ia]
            miss = rng.random(ia.size) < r_fn(o)
            S[ia] = np.maximum(0.0, S[ia] + np.where(miss, a, b))
            hit = S[ia] > h
            T[ia[hit]] = o[hit] + d
            alive[ia[hit]] = False
        T_all.append(T)
    return np.concatenate(T_all)


def timely_fa(h, p, pi, q, d, n_rep=200000, seed=1, tau=10000, D=10000, H=29999, r_pre=0.05, r1=0.20):
    rho = pi * q
    T = simulate(h, p, rho, lambda o: np.where(o < tau, r_pre, r1), tau + D - 1 - d, d, n_rep, seed)
    timely = np.mean((T >= tau) & (T <= tau + D - 1))
    early = np.mean((T >= 0) & (T < tau))
    Tf = simulate(h, p, rho, lambda o: np.full(o.shape, 0.10), H - d, d, n_rep, seed + 1000)
    fa = np.mean(Tf >= 0)
    se = lambda x: np.sqrt(x * (1 - x) / n_rep)
    return dict(timely=timely, timely_se=se(timely), early=early, fa=fa, fa_se=se(fa))
